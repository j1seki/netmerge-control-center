// Command docgen renders the error-code registry as the Markdown table in
// docs/ERROR-CODES.md. It exists so the documentation cannot drift from the registry: the
// registry is the source, the document is generated from it, and a test asserts the document
// lists every code.
//
//	go run ./internal/errcodes/docgen > docs/ERROR-CODES.md
package main

import (
	"fmt"
	"os"
	"strings"

	"net-merge/internal/errcodes"
)

func main() {
	out := os.Stdout
	fmt.Fprintln(out, "<!-- Generated by `go run ./internal/errcodes/docgen`. Do not edit by hand: edit")
	fmt.Fprintln(out, "     internal/errcodes/errcodes.go and regenerate, or the test that keeps the two in")
	fmt.Fprintln(out, "     step will fail. -->")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "# Error and event codes")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "Every code the application can show a person is listed here with what it means and, for")
	fmt.Fprintln(out, "errors and refusals, what to do next. Codes are stable identifiers: they are what the log,")
	fmt.Fprintln(out, "the dashboard and an exported report all quote, so wording can change without breaking")
	fmt.Fprintln(out, "anything that reads them.")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "| Code | Kind | What it means | What to do |")
	fmt.Fprintln(out, "|---|---|---|---|")
	for _, e := range errcodes.All() {
		fix := e.Fix
		if fix == "" {
			fix = "—"
		}
		fmt.Fprintf(out, "| `%s` | %s | %s | %s |\n", e.Code, e.Kind, table(e.Meaning), table(fix))
	}
	fmt.Fprintln(out)
	fmt.Fprintf(out, "Registry size: %d code(s).\n", len(errCodes()))
}

func errCodes() []errcodes.Entry { return errcodes.All() }

// table keeps generated prose safe for a Markdown table.
func table(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}
